// node validators.mjs BUNDLE OUT: writes, to OUT, Ajv standalone validators for
// the JSON success responses of the operations listed below, keyed by
// "METHOD path status" as the Web client's middleware looks them up
// (web/src/api.ts). Standalone code needs no eval at run time, which the
// desktop's Content-Security-Policy would refuse.
import { readFileSync, writeFileSync } from "node:fs";

import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { load } from "js-yaml";

// The responses the desktop shell renders outside any window's error
// boundary: sign-in, the status bar, the rail, notifications, people, the
// wallpaper, the app shortcuts, VNAS, the share reminders (SharesProvider),
// the transfer indicator and toasts (transfers/store.ts, which keeps what
// downloads, pauses and cancels answer) and the feedback panel with its
// threads, whose writes answer with the item it lists. Also those whose
// clients used to check their shape by hand. A body that breaks the contract
// fails the call instead of the desktop (docs/investigations/2026-10-07-blank-disk-plan-ui-crash.md).
// Each needs a Go contract test, so that the server keeps to what is checked.
const VALIDATED = [
  "getSetupStatus",
  "setupAdministrator",
  "getSession",
  "createSession",
  "getHostState",
  "getHostMetrics",
  "listNotifications",
  "listProfiles",
  "getWallpaper",
  "getLocalDisplay",
  "listAppShortcuts",
  "getAssistantStatus",
  "listShareNotifications",
  "listMemberShares",
  "getMemberShare",
  "listShareMessages",
  "listTransfers",
  "getTransfer",
  "createDownload",
  "pauseUpload",
  "cancelTransfer",
  "listFeedback",
  "createFeedback",
  "editFeedback",
  "resolveFeedback",
  "addFeedbackComment",
  "editFeedbackComment",
  "deleteFeedbackComment",
  "getTerminalStatus",
  "listApps",
  "getAppInstallPlan",
  "getContainerSnapshot",
];

const [bundlePath, outPath] = process.argv.slice(2);
const bundle = load(readFileSync(bundlePath, "utf8"));
const pointer = (...parts) => "#/" + parts.map((part) => encodeURIComponent(part.replaceAll("~", "~0").replaceAll("/", "~1"))).join("/");

// The check is of shape: types, required fields, enums, nulls. Formats and
// string lengths are left to the server, which counts a nickname's length in
// characters; Ajv's standalone code would count UTF-16 units, or need Ajv at
// run time to count characters, and a string of any length breaks no desktop.
// Error messages and inlined references would only make the code larger.
const ajv = new Ajv2020({
  strict: false,
  validateFormats: false,
  messages: false,
  inlineRefs: false,
  code: { source: true, esm: true, lines: true },
});
ajv.removeKeyword("minLength");
ajv.removeKeyword("maxLength");
ajv.addSchema(bundle, "openapi.json");

const exports = {};
const keys = [];
const found = new Set();
for (const [path, item] of Object.entries(bundle.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    if (!VALIDATED.includes(operation?.operationId)) continue;
    found.add(operation.operationId);
    for (const [status, response] of Object.entries(operation.responses)) {
      if (!/^2\d\d$/.test(status) || !response.content?.["application/json"]?.schema) continue;
      const name = `validate${keys.length}`;
      ajv.addSchema({ $ref: `openapi.json${pointer("paths", path, method, "responses", status, "content", "application/json", "schema")}` }, name);
      exports[name] = name;
      keys.push([`${method.toUpperCase()} ${path} ${status}`, name]);
    }
  }
}
const missing = VALIDATED.filter((operationId) => !found.has(operationId));
if (missing.length) throw new Error(`no such operation in the contract: ${missing.join(", ")}`);

const code = standaloneCode(ajv, exports);
if (/\brequire\(/.test(code)) throw new Error("the validators need Ajv at run time; keep to keywords standalone code covers itself");
writeFileSync(
  outPath,
  `// @ts-nocheck
// Generated by \`make api\` (tools/openapi/validators.mjs) from api/openapi.bundle.yaml with Ajv. Do not edit.
${code}
export const responseValidators: Record<string, { (data: unknown): boolean; errors?: unknown[] | null }> = {
${keys.map(([key, name]) => `  ${JSON.stringify(key)}: ${name},`).join("\n")}
};
`,
);
